export type SegmentType = 
  | 'LADEN_VOYAGE'
  | 'BALLAST_VOYAGE'
  | 'PORT_LOADING'
  | 'PORT_DISCHARGE'
  | 'PORT_ANCHORAGE'
  | 'MAINTENANCE_DRYDOCK'
  | 'MAINTENANCE_ENGINE'
  | 'MAINTENANCE_HULL'
  | 'MAINTENANCE_HOLDS'
  | 'MAINTENANCE_BWTS'
  | 'BUNKERING_CALL';

export type SegmentStatus = 'COMPLETED' | 'IN_PROGRESS' | 'SCHEDULED' | 'DELAYED' | 'WARNING';

export interface TimelineSegment {
  id: string;
  vesselId: string;
  vesselName: string;
  type: SegmentType;
  title: string;
  shortLabel: string;
  startDate: string; // ISO date YYYY-MM-DD or YYYY-MM-DDTHH:mm
  endDate: string;
  durationDays: number;
  status: SegmentStatus;
  
  // Location & Corridor
  originPort?: string;
  destinationPort?: string;
  locationName: string; // Port, Sea Area, or Shipyard
  corridorOrYard?: string;
  
  // Operational details for Voyages
  cargoType?: string;
  cargoQuantityMT?: number;
  draftLadenM?: number;
  speedMode?: 'LADEN_FULL' | 'ECO_SPEED' | 'VIRTUAL_ARRIVAL' | 'BALLAST_MAX';
  avgSpeedKts?: number;
  estimatedDistanceNM?: number;
  bunkerConsumptionMT?: number;
  laycanWindow?: { start: string; end: string };
  demurrageRatePerDayUSD?: number;
  
  // Operational details for Maintenance
  shipyardName?: string;
  drydockNumber?: string;
  classSurveyor?: string; // DNV, Lloyd's Register, ClassNK, ABS, IRS
  workScope?: string[];
  maintenanceBudgetUSD?: number;
  offHireDays?: number;
  ciiEfficiencyGainPct?: number; // e.g. +3.5% post hull grooming
  isClassMandated?: boolean;
  
  // Notes and risk flags
  description: string;
  operationalNotes?: string;
  hasConflictWarning?: boolean;
  conflictDetails?: string;
  progressPct?: number; // for in-progress segments
}

